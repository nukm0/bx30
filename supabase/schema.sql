-- Marketplace production persistence. Run this in the Supabase SQL editor.
create extension if not exists pgcrypto;
create table if not exists public.marketplace_users (
  telegram_id bigint primary key,
  username text,
  first_name text,
  last_name text,
  photo_url text,
  verified boolean not null default false,
  verified_by bigint,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.marketplace_staff_roles (
  telegram_id bigint primary key,
  role text not null check (role in ('Заместитель владельца','Администратор','Модератор','Стажёр','Магазин')),
  assigned_by bigint not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.marketplace_shops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null default '',
  logo_url text,
  owner_telegram_id bigint not null unique,
  created_by bigint not null,
  created_at timestamptz not null default now(),
  hidden boolean not null default false
);
create table if not exists public.marketplace_shop_subscriptions (
  shop_id uuid not null references public.marketplace_shops(id) on delete cascade,
  telegram_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (shop_id, telegram_id)
);
create table if not exists public.marketplace_banners (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  image_url text,
  target_url text,
  show_home boolean not null default true,
  show_shops boolean not null default false,
  hidden boolean not null default false,
  created_by bigint not null,
  created_at timestamptz not null default now()
);
create table if not exists public.marketplace_reports (
  id uuid primary key default gen_random_uuid(),
  reporter_telegram_id bigint not null,
  object_type text not null,
  object_id text,
  object_title text not null default '',
  object_owner_username text,
  object_owner_telegram_id bigint,
  reason text not null,
  details text not null,
  materials jsonb not null default '[]'::jsonb,
  status text not null default 'new',
  reviewer_telegram_id bigint,
  reviewer_username text,
  review_comment text,
  recommended_action text,
  recommended_duration_minutes integer,
  owner_telegram_id bigint,
  owner_comment text,
  owner_decision text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create table if not exists public.marketplace_bans (
  id uuid primary key default gen_random_uuid(),
  telegram_id bigint not null,
  reason text not null,
  permanent boolean not null default false,
  expires_at timestamptz,
  active boolean not null default true,
  created_by bigint not null,
  created_at timestamptz not null default now()
);
create index if not exists marketplace_bans_active_user_idx on public.marketplace_bans(telegram_id, active, created_at desc);
create table if not exists public.marketplace_listing_moderation (
  object_type text not null,
  object_id text not null,
  public_hidden boolean not null default false,
  admin_queue_hidden boolean not null default false,
  reason text,
  updated_by bigint not null,
  updated_at timestamptz not null default now(),
  primary key (object_type, object_id)
);
create table if not exists public.marketplace_admin_audit (
  id bigint generated by default as identity primary key,
  actor_telegram_id bigint not null,
  actor_username text,
  actor_name text,
  action text not null,
  target text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.marketplace_faq_entries (
  id uuid primary key default gen_random_uuid(),
  section text not null,
  heading text not null default '',
  parent_heading text not null default '',
  question text not null,
  answer text not null,
  created_by bigint not null,
  created_at timestamptz not null default now()
);
-- Keep all write access server-side. Never expose the service role key to the browser.
alter table public.marketplace_users enable row level security;
alter table public.marketplace_staff_roles enable row level security;
alter table public.marketplace_shops enable row level security;
alter table public.marketplace_shop_subscriptions enable row level security;
alter table public.marketplace_banners enable row level security;
alter table public.marketplace_reports enable row level security;
alter table public.marketplace_bans enable row level security;
alter table public.marketplace_listing_moderation enable row level security;
alter table public.marketplace_admin_audit enable row level security;
alter table public.marketplace_faq_entries enable row level security;
create table if not exists public.marketplace_notifications (
  id uuid primary key default gen_random_uuid(),
  telegram_id bigint not null,
  title text not null,
  message text not null,
  read boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.marketplace_notifications enable row level security;
